	FOREIGN KEY (ID_AVALIACAO) REFERENCES AVALIACAO (ID),
	FOREIGN KEY (ID_TURMA) REFERENCES TURMA (ID)
);

CREATE TABLE AVALIACAO_NOTA (
	ID_NOTA INTEGER PRIMARY KEY,
	ID_AVALIACAO INTEGER NOT NULL,
	FOREIGN KEY (ID_NOTA) REFERENCES NOTA (ID),
	FOREIGN KEY (ID_AVALIACAO) REFERENCES AVALIACAO (ID)
);

CREATE TABLE MATERIAL_PROFESSOR (
	ID SERIAL PRIMARY KEY,
	ID_MATERIAL INTEGER NOT NULL,
	ID_PROFESSOR INTEGER NOT NULL,
	FOREIGN KEY (ID_MATERIAL) REFERENCES MATERIAL_DIDATICO (ID),
	FOREIGN KEY (ID_PROFESSOR) REFERENCES PROFESSOR (ID)
);

CREATE TABLE MATERIAL_TURMA (
	ID SERIAL PRIMARY KEY,
	ID_MATERIAL INTEGER NOT NULL,
	ID_TURMA VARCHAR(20) NOT NULL,
	FOREIGN KEY (ID_MATERIAL) REFERENCES MATERIAL_DIDATICO (ID),
	FOREIGN KEY (ID_TURMA) REFERENCES TURMA (ID)
);

CREATE TABLE PROFESSOR_PROJETO (
	ID SERIAL PRIMARY KEY,
	ID_PROFESSOR INTEGER NOT NULL,
	ID_PROJETO INTEGER NOT NULL,
	FUNCAO VARCHAR(60) NOT NULL CHECK (FUNCAO <> ''),
	FOREIGN KEY (ID_PROFESSOR) REFERENCES PROFESSOR (ID),
	FOREIGN KEY (ID_PROJETO) REFERENCES PROJETO_PESQUISA (ID),
	UNIQUE (ID_PROJETO, FUNCAO)
);

