CREATE TYPE ESTADO_TURMA AS ENUM('ativo', 'encerrado', 'cancelado');

CREATE TYPE TIPO_AVALIACAO AS ENUM('prova', 'trabalho');

CREATE TYPE TIPO_ESTRUTURA AS ENUM('anfiteatro', 'laboratorio', 'sala_comum');

CREATE TYPE TIPO_LOUSA AS ENUM('branca', 'preta', 'digital');

CREATE TYPE FORMATO_MATERIAL AS ENUM('pdf', 'video', 'audio', 'livro');

CREATE TYPE REGIME_CURSO AS ENUM('semestre', 'anual');

CREATE TYPE ESTADO_PROJETO AS ENUM('planejado', 'em_andamento', 'finalizado');

CREATE TABLE CURSO (
	ID SERIAL PRIMARY KEY,
	NOME VARCHAR(60) UNIQUE NOT NULL,
	ID_COORDENADOR INTEGER NOT NULL,
	REGIME REGIME_CURSO NOT NULL,
	DURACAO INTEGER NOT NULL
);

CREATE TABLE PROFESSOR (
	ID SERIAL PRIMARY KEY,
	NOME VARCHAR(60) NOT NULL,
	AREA_PROFESSOR VARCHAR(60) NOT NULL,
	ID_CURSO INTEGER,
	CONTATO VARCHAR(60),
	FOREIGN KEY (ID_CURSO) REFERENCES CURSO (ID)
);

