CREATE TABLE IF NOT EXISTS DISCIPLINA (
	NUMERO_DISCIPLINA SERIAL NOT NULL,
	AREA_DISCIPLINA VARCHAR(60) NOT NULL CHECK (LENGTH(AREA_DISCIPLINA) >= 2),
	ID VARCHAR(20) GENERATED ALWAYS AS (
		SUBSTRING(
			AREA_DISCIPLINA
			FROM
				1 FOR 2
		) || NUMERO_DISCIPLINA::TEXT
	) STORED,
	NOME VARCHAR(60) NOT NULL CHECK (NOME <> ''),
	CARGA_HORARIA INTEGER NOT NULL,
	EMENTA TEXT NOT NULL CHECK (EMENTA <> ''),
	PRIMARY KEY (ID)
);

CREATE TABLE IF NOT EXISTS TURMA (
	ID_DISCIPLINA VARCHAR(20) NOT NULL,
	ID_CURSO INTEGER NOT NULL,
	nome_curso VARCHAR(60) NOT NULL, 
	numero_disciplina INTEGER not null, 
	ID VARCHAR(20) PRIMARY KEY GENERATED ALWAYS AS (
		SUBSTRING(
			NOME_CURSO
			FROM 
				1 FOR 2
		) || NUMERO_DISCIPLINA::TEXT
	) STORED,
	NOME VARCHAR(60) NOT NULL CHECK (NOME <> ''),
	SEMESTRE INTEGER NOT NULL,
	CAP_MAXIMA INTEGER NOT NULL,
	ESTADO ESTADO_TURMA NOT NULL,
	FOREIGN KEY (ID_CURSO) REFERENCES CURSO (ID),
	FOREIGN KEY (ID_DISCIPLINA) REFERENCES DISCIPLINA (ID)
	-- PRIMARY KEY (ID)
);

CREATE OR REPLACE FUNCTION sync_nome_curso_with_turma()
RETURNS TRIGGER AS $$
BEGIN
    -- Update 'nome_curso' em TURMA quando CURSO realiza update
    UPDATE TURMA
    SET nome_curso = NEW.NOME
    WHERE TURMA.ID_CURSO = NEW.ID;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION sync_numero_disciplina_with_turma()
RETURNS TRIGGER AS $$
BEGIN
    -- Update 'numero_disciplina' em TURMA quando DISCIPLINA realiza update
    UPDATE TURMA
    SET numero_disciplina = NEW.NUMERO_DISCIPLINA
    WHERE TURMA.ID_DISCIPLINA = NEW.ID;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_sync_nome_curso_with_turma
AFTER UPDATE OF NOME
ON CURSO
FOR EACH ROW
EXECUTE FUNCTION sync_nome_curso_with_turma();

CREATE TRIGGER trg_sync_numero_disciplina_with_turma
AFTER UPDATE OF NUMERO_DISCIPLINA
ON DISCIPLINA
FOR EACH ROW
EXECUTE FUNCTION sync_numero_disciplina_with_turma();



CREATE TABLE IF NOT EXISTS ALUNO (
	ID SERIAL PRIMARY KEY,
	MATRICULA CHAR(6) UNIQUE NOT NULL CHECK (MATRICULA ~ '^[0-9]{6}$'),
	NOME VARCHAR(60) NOT NULL CHECK (NOME <> ''),
	ID_CURSO INTEGER NOT NULL,
	NASCIMENTO DATE NOT NULL,
	ENTRADA INTEGER NOT NULL,
	CONCLUSAO INTEGER NOT NULL,
	CHECK (ENTRADA <= CONCLUSAO),
	FOREIGN KEY (ID_CURSO) REFERENCES CURSO (ID)
