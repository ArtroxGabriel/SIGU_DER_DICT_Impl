	FOREIGN KEY (ID_ALUNO) REFERENCES ALUNO (ID),
	FOREIGN KEY (ID_PROJETO) REFERENCES PROJETO_PESQUISA (ID),
	UNIQUE (ID_PROJETO, FUNCAO)
);