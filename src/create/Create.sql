	FOREIGN KEY (ID_DISCIPLINA) REFERENCES DISCIPLINA (ID),
	FOREIGN KEY (ID_MATERIAL) REFERENCES MATERIAL_DIDATICO (ID)
);

CREATE TABLE ALUNO_TURMA (
