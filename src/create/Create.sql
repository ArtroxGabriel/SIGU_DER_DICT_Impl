-- TRIGGER para orc disponivel
CREATE TABLE IF NOT EXISTS PROJETO_PESQUISA (
	ID SERIAL PRIMARY KEY,
	TITULO VARCHAR(60) NOT NULL CHECK (TITULO <> ''),
	ID_COORDENADOR INTEGER NOT NULL,
	AREA VARCHAR(60) NOT NULL CHECK (AREA <> ''),
	DESCRICAO VARCHAR(255) NOT NULL CHECK (DESCRICAO <> ''),
	ORC_PLANEJADO REAL NOT NULL,
	ORC_REALIZADO REAL,
	ORC_DISPONIVEL REAL,
	ESTADO ESTADO_PROJETO NOT NULL,
	FOREIGN KEY (ID_COORDENADOR) REFERENCES PROFESSOR (ID),
	CHECK (ORC_REALIZADO IS NULL OR ORC_REALIZADO <= ORC_PLANEJADO)
);

-- Função de calculo do orc_disponivel na tablea PROJETO_PESQUISA
CREATE OR REPLACE FUNCTION calculate_orc_disponivel()
RETURNS TRIGGER AS $$
BEGIN
    -- Calcula ORC_DISPONIVEL como ORC_PLANEJADO - ORC_REALIZADO
    NEW.ORC_DISPONIVEL := NEW.ORC_PLANEJADO - COALESCE(NEW.ORC_REALIZADO, 0);
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_calculate_orc_disponivel
BEFORE INSERT OR UPDATE OF ORC_REALIZADO ON PROJETO_PESQUISA
FOR EACH ROW
EXECUTE FUNCTION calculate_orc_disponivel();


